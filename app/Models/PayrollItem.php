<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

class PayrollItem extends Model
{
    use HasFactory;

    /*
    |--------------------------------------------------------------------------
    | Mass Assignment
    |--------------------------------------------------------------------------
    */

    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | Relationships
        |--------------------------------------------------------------------------
        */

        'payroll_run_id',
        'staff_id',

        /*
        |--------------------------------------------------------------------------
        | Employee Snapshot
        |--------------------------------------------------------------------------
        */

        'employee_number',
        'first_name',
        'last_name',
        'id_number',
        'tax_number',
        'employment_type',
        'position',
        'branch',

        /*
        |--------------------------------------------------------------------------
        | Employment
        |--------------------------------------------------------------------------
        */

        'start_date',
        'termination_date',
        'termination_reason',

        /*
        |--------------------------------------------------------------------------
        | Hours
        |--------------------------------------------------------------------------
        */

        'hours_worked',
        'ordinary_hours',
        'overtime_hours',

        /*
        |--------------------------------------------------------------------------
        | Earnings
        |--------------------------------------------------------------------------
        */

        'basic_salary',
        'overtime_amount',
        'allowances',
        'bonus',
        'commission',
        'other_earnings',
        'gross_salary',

        /*
        |--------------------------------------------------------------------------
        | UIF
        |--------------------------------------------------------------------------
        */

        'uif_liable_amount',
        'employee_uif',
        'employer_uif',
        'uif_liable',
        'uif_exclusion_code',

        /*
        |--------------------------------------------------------------------------
        | PAYE
        |--------------------------------------------------------------------------
        */

        'taxable_income',
        'paye',

        /*
        |--------------------------------------------------------------------------
        | SDL
        |--------------------------------------------------------------------------
        */

        'sdl_liable_amount',
        'sdl',

        /*
        |--------------------------------------------------------------------------
        | Deductions
        |--------------------------------------------------------------------------
        */

        'loan_deduction',
        'leave_deduction',
        'other_deductions',
        'total_deductions',

        /*
        |--------------------------------------------------------------------------
        | Net
        |--------------------------------------------------------------------------
        */

        'net_salary',
        'employer_cost',

        /*
        |--------------------------------------------------------------------------
        | Leave
        |--------------------------------------------------------------------------
        */

        'annual_leave_taken',
        'annual_leave_balance',

        'sick_leave_taken',
        'sick_leave_balance',

        'family_leave_taken',
        'family_leave_balance',

        /*
        |--------------------------------------------------------------------------
        | Calculation
        |--------------------------------------------------------------------------
        */

        'calculation_data',

        /*
        |--------------------------------------------------------------------------
        | Status
        |--------------------------------------------------------------------------
        */

        'status',
        'exclusion_reason',
    ];

    /*
    |--------------------------------------------------------------------------
    | Casts
    |--------------------------------------------------------------------------
    */

    protected $casts = [

        /*
        |--------------------------------------------------------------------------
        | Employment Dates
        |--------------------------------------------------------------------------
        */

        'start_date' => 'date',

        'termination_date' => 'date',

        /*
        |--------------------------------------------------------------------------
        | Hours
        |--------------------------------------------------------------------------
        */

        'hours_worked' => 'decimal:2',

        'ordinary_hours' => 'decimal:2',

        'overtime_hours' => 'decimal:2',

        /*
        |--------------------------------------------------------------------------
        | Earnings
        |--------------------------------------------------------------------------
        */

        'basic_salary' => 'decimal:2',

        'overtime_amount' => 'decimal:2',

        'allowances' => 'decimal:2',

        'bonus' => 'decimal:2',

        'commission' => 'decimal:2',

        'other_earnings' => 'decimal:2',

        'gross_salary' => 'decimal:2',

        /*
        |--------------------------------------------------------------------------
        | UIF
        |--------------------------------------------------------------------------
        */

        'uif_liable_amount' => 'decimal:2',

        'employee_uif' => 'decimal:2',

        'employer_uif' => 'decimal:2',

        'uif_liable' => 'boolean',

        /*
        |--------------------------------------------------------------------------
        | PAYE
        |--------------------------------------------------------------------------
        */

        'taxable_income' => 'decimal:2',

        'paye' => 'decimal:2',

        /*
        |--------------------------------------------------------------------------
        | SDL
        |--------------------------------------------------------------------------
        */

        'sdl_liable_amount' => 'decimal:2',

        'sdl' => 'decimal:2',

        /*
        |--------------------------------------------------------------------------
        | Deductions
        |--------------------------------------------------------------------------
        */

        'loan_deduction' => 'decimal:2',

        'leave_deduction' => 'decimal:2',

        'other_deductions' => 'decimal:2',

        'total_deductions' => 'decimal:2',

        /*
        |--------------------------------------------------------------------------
        | Net
        |--------------------------------------------------------------------------
        */

        'net_salary' => 'decimal:2',

        'employer_cost' => 'decimal:2',

        /*
        |--------------------------------------------------------------------------
        | Leave
        |--------------------------------------------------------------------------
        */

        'annual_leave_taken' => 'decimal:2',

        'annual_leave_balance' => 'decimal:2',

        'sick_leave_taken' => 'decimal:2',

        'sick_leave_balance' => 'decimal:2',

        'family_leave_taken' => 'decimal:2',

        'family_leave_balance' => 'decimal:2',

        /*
        |--------------------------------------------------------------------------
        | Calculation Snapshot
        |--------------------------------------------------------------------------
        */

        'calculation_data' => 'array',
    ];

    /*
    |--------------------------------------------------------------------------
    | Payroll Run
    |--------------------------------------------------------------------------
    */

    public function payrollRun(): BelongsTo
    {
        return $this->belongsTo(
            PayrollRun::class,
            'payroll_run_id'
        );
    }

    
    /*
    |--------------------------------------------------------------------------
    | Staff
    |--------------------------------------------------------------------------
    */

    public function staff(): BelongsTo
    {
        return $this->belongsTo(
            Staff::class,
            'staff_id'
        );
    }

    /*
    |--------------------------------------------------------------------------
    | Payment Items
    |--------------------------------------------------------------------------
    |
    | A payroll item can have payment records associated with it.
    |
    */

    public function paymentItems(): HasMany
    {
        return $this->hasMany(
            PaymentItem::class,
            'payroll_item_id'
        );
    }

    /*
    |--------------------------------------------------------------------------
    | Status Helpers
    |--------------------------------------------------------------------------
    */

    public function isCalculated(): bool
    {
        return $this->status === 'calculated';
    }

    public function isExcluded(): bool
    {
        return $this->status === 'excluded';
    }

    /*
    |--------------------------------------------------------------------------
    | Full Employee Name
    |--------------------------------------------------------------------------
    */

    public function getEmployeeNameAttribute(): string
    {
        return trim(
            ($this->first_name ?? '') .
            ' ' .
            ($this->last_name ?? '')
        );
    }

    /*
    |--------------------------------------------------------------------------
    | Total Employer Statutory Cost
    |--------------------------------------------------------------------------
    */

    public function getEmployerStatutoryCostAttribute(): float
    {
        return round(
            (float) $this->employer_uif +
            (float) $this->sdl,
            2
        );
    }

    /*
    |--------------------------------------------------------------------------
    | Employer Cost
    |--------------------------------------------------------------------------
    */

    public function getCalculatedEmployerCostAttribute(): float
    {
        return round(
            (float) $this->gross_salary +
            (float) $this->employer_uif +
            (float) $this->sdl,
            2
        );
    }
}